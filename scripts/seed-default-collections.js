// One-shot helper: add a default collection to every repository in
// genealogy-free-resources.js that doesn't already have collections[].
// Run once: `node scripts/seed-default-collections.js`. Re-running is
// idempotent — entries that already have collections are left alone.

const fs = require('fs');
const path = require('path');

const DATA_PATH = path.join(__dirname, '..', 'resources', 'genealogy-free-resources.js');
const JSON_PATH = path.join(__dirname, '..', 'resources', 'genealogy-free-resources.json');

global.window = {};
require(DATA_PATH);
const resources = global.window.GENEALOGY_RESOURCES;

const EVENT_LABELS = {
  birth: 'Births', baptism: 'Baptisms', marriage: 'Marriages', death: 'Deaths',
  burial: 'Burials', census: 'Census', residence: 'Residence', military: 'Military',
  travel: 'Travel', legal: 'Court', employment: 'Employment', education: 'Education',
  other: 'Records',
};

function spanLabel(start, end) {
  if (start && end) return start + '\u2013' + end;
  if (start) return 'from ' + start;
  if (end) return 'to ' + end;
  return '';
}

function defaultCollection(r) {
  const cov = (r.coverage && r.coverage[0]) || {};
  const events = Array.isArray(cov.events) ? cov.events.slice() : [];
  // Title piece: list up to 3 distinctive event labels when the scope is
  // narrow; collapse to "All records" for broad-scope repositories that
  // cover six or more event types — listing 3 of 12 misrepresents the rest.
  const distinctive = events.filter((e) => e !== 'other');
  const eventPiece = events.length === 0 ? 'Records'
    : distinctive.length >= 6 ? 'All records'
    : distinctive.slice(0, 3).map((e) => EVENT_LABELS[e] || e).join(', ');
  const span = spanLabel(cov.startYear, cov.endYear);
  const name = (eventPiece + (span ? ' ' + span : '')).trim();
  return {
    id: r.id + '-default',
    name,
    url: r.url || r.homeUrl,
    coverage: r.coverage || [],
    notes: 'Catch-all collection covering this repository\u2019s main holdings. Refine the title with the specific dataset when you cite a record.',
  };
}

let touched = 0;
for (const r of resources) {
  // Drop any existing auto-generated default so re-runs pick up improvements.
  if (Array.isArray(r.collections)) {
    r.collections = r.collections.filter((c) => c.id !== r.id + '-default');
  }
  if (!Array.isArray(r.collections) || r.collections.length === 0) {
    r.collections = [defaultCollection(r)];
    touched++;
  }
}

const HEADER =
  '// Auto-generated by scripts/transform-data.js. Edit this file directly OR\n' +
  '// edit the script and re-run. The JSON snapshot at\n' +
  '// resources/genealogy-free-resources.json is regenerated alongside.\n';

const JS_OUT = HEADER + 'window.GENEALOGY_RESOURCES = ' + JSON.stringify(resources, null, 2) + ';\n';
const JSON_OUT = JSON.stringify(resources, null, 2) + '\n';

fs.writeFileSync(DATA_PATH, JS_OUT);
fs.writeFileSync(JSON_PATH, JSON_OUT);

console.log('Seeded default collections for ' + touched + ' of ' + resources.length + ' repositories.');
